// How the work was handed off at completion.
export type VisitFulfilmentMethod = 'in_person' | 'shipping';

// Looks at the active cart for the visit and decides whether the
// Complete visit flow needs to ask the in-person / shipping
// question. Returns false when every active line came from a
// catalogue row with fulfilment_required=false (virtual sessions,
// in-person impression appointments). Returns true when at least
// one line still needs a fulfilment decision — that's the safe
// default whenever we can't read the catalogue or the cart contains
// a free-form (no catalogue_id) line, since asking is preferable to
// silently auto-completing a real handover.
export async function visitRequiresFulfilment(visitId: string): Promise<boolean> {
  const { data: cart } = await supabase
    .from('lng_carts')
    .select('id')
    .eq('visit_id', visitId)
    .maybeSingle();
  const cartId = (cart as { id: string } | null)?.id;
  if (!cartId) return true;

  const { data: rows, error } = await supabase
    .from('lng_cart_items')
    .select('catalogue_id')
    .eq('cart_id', cartId)
    .is('removed_at', null);
  if (error) return true;

  const items = (rows ?? []) as Array<{ catalogue_id: string | null }>;
  if (items.length === 0) return false;

  // Any ad-hoc line (no catalogue_id) forces the question — we can't
  // know what it represents physically.
  if (items.some((i) => !i.catalogue_id)) return true;

  const catalogueIds = Array.from(
    new Set(items.map((i) => i.catalogue_id).filter((id): id is string => !!id)),
  );
  if (catalogueIds.length === 0) return true;

  const { data: cat, error: catErr } = await supabase
    .from('lwo_catalogue')
    .select('id, fulfilment_required')
    .in('id', catalogueIds);
  if (catErr) return true;

  const flagById = new Map<string, boolean>();
  for (const row of (cat ?? []) as Array<{ id: string; fulfilment_required: boolean }>) {
    flagById.set(row.id, row.fulfilment_required);
  }

  // Default to requiring fulfilment when a catalogue row is missing
  // (renamed / deleted) so we never silently auto-complete a real
  // physical handover.
  return items.some((i) => flagById.get(i.catalogue_id!) !== false);
}

export interface CompleteVisitInput {
  patient_id: string;
  visit_id: string;
  appointment_id: string | null;
  walk_in_id: string | null;
  // Null means "no fulfilment needed for this visit" — every active
  // cart line came from a catalogue row with fulfilment_required=false
  // (virtual sessions, in-person impression appointments). The Complete
  // visit flow skips the fulfilment sheet in this case and finishes
  // directly. Non-null records the staff's in-person/shipping choice.
  fulfilment_method: VisitFulfilmentMethod | null;
  // Total in pence — used purely for the timeline event payload so
  // the closed event reads "£298.00" without a join back to the
  // cart roll-up.
  total_pence?: number;
}

// Explicit visit completion. Until now Pay auto-completed the visit
// when staff sent the receipt; that conflated payment with hand-off
// and skipped the in-person-vs-shipping question. Now staff has to
// click Complete visit on VisitDetail and answer the fulfilment
// question, which lands as fulfilment_method on the visit row for a
// future shipping flow to pick up.
//
// Side effects:
//   - flips lng_visits.status='complete' + stamps closed_at
//   - records fulfilment_method (in_person | shipping)
//   - frees the job box on the appointment / walk_in source so the
//     box becomes available for the next booking (the visit's own
//     jb_ref column is captured at insert and stays as audit)
//   - writes a patient_events 'visit_closed' row with the staff
//     account and the fulfilment choice on the payload
export async function completeVisit(input: CompleteVisitInput): Promise<void> {
  const { data: accountId } = await supabase.rpc('auth_account_id');

  const closedAt = new Date().toISOString();

  const { error: visitErr } = await supabase
    .from('lng_visits')
    .update({
      status: 'complete',
      closed_at: closedAt,
      fulfilment_method: input.fulfilment_method,
    })
    .eq('id', input.visit_id);
  if (visitErr) throw new Error(visitErr.message);

  // Seal the cart at the same moment as the visit. Without this a
  // free-visit (£0 balance) cart stays status='open' after Complete
  // because maybeFlipCartPaid only flips carts whose succeeded
  // payments meet a positive total — a £0 cart never trips that
  // condition. The open-after-complete state was both visually
  // confusing ("Cart open" pill on a Complete visit) and editable
  // (staff or an automated path could still add lines / discounts
  // against a visit that's already been physically handed off).
  // We close the cart unconditionally on completion; the UI gates
  // Complete visit on the cart already being settled (paid in full
  // or £0), so flipping to status='paid' here is consistent with
  // what the receptionist already saw before clicking Complete.
  await supabase
    .from('lng_carts')
    .update({ status: 'paid', closed_at: closedAt })
    .eq('visit_id', input.visit_id)
    .eq('status', 'open');

  // Free the JB and flip the source row to 'complete' so the
  // schedule calendar shows the appointment/walk-in as done.
  // The visit's own captured jb_ref is immutable and survives
  // this clearing, so the timeline + history stay intact.
  if (input.appointment_id) {
    const { error } = await supabase
      .from('lng_appointments')
      .update({ jb_ref: null, status: 'complete' })
      .eq('id', input.appointment_id);
    if (error) {
      await logFailure({
        source: 'visits.completeVisit.appointment_status',
        severity: 'error',
        message: `Visit completed but the appointment row did not flip to complete: ${error.message}`,
        context: { visit_id: input.visit_id, appointment_id: input.appointment_id },
      });
    }
  }
  if (input.walk_in_id) {
    const { error: walkInErr } = await supabase
      .from('lng_walk_ins')
      .update({ jb_ref: null })
      .eq('id', input.walk_in_id);
    if (walkInErr) {
      await logFailure({
        source: 'visits.completeVisit.walk_in_jb',
        severity: 'error',
        message: `Visit completed but the walk-in job box was not freed: ${walkInErr.message}`,
        context: { visit_id: input.visit_id, walk_in_id: input.walk_in_id },
      });
    }

    // Walk-ins carry a second row the schedule actually reads: the
    // calendar marker in lng_appointments written by openWalkInVisit
    // with status='arrived' and walk_in_id pointing back here. The
    // visit's own appointment_id stays NULL for walk-ins (the
    // exactly-one constraint on lng_visits forces walk_in_id
    // instead), so the branch above never fires for them and the
    // marker was left on 'arrived' forever. isAppointmentDimmed
    // treats 'arrived' as an active visit and refuses to dim it at
    // any age, so a fully processed walk-in kept rendering at full
    // strength with an "Arrived" pill days after the patient left.
    // Flip the marker here so walk-ins reach the same terminal
    // state as booked appointments. Status only: a walk-in's job box
    // lives on lng_walk_ins.jb_ref (the marker is inserted without
    // one, and clinicBoard reads the walk-in row for it), and the
    // branch above already freed it.
    const { error: markerErr } = await supabase
      .from('lng_appointments')
      .update({ status: 'complete' })
      .eq('walk_in_id', input.walk_in_id);
    if (markerErr) {
      await logFailure({
        source: 'visits.completeVisit.walk_in_marker_status',
        severity: 'error',
        message: `Visit completed but the walk-in calendar marker did not flip to complete: ${markerErr.message}`,
        context: { visit_id: input.visit_id, walk_in_id: input.walk_in_id },
      });
    }
  }

  await supabase.from('patient_events').insert({
    patient_id: input.patient_id,
    event_type: 'visit_closed',
    actor_account_id: (accountId as string | null) ?? null,
    payload: {
      visit_id: input.visit_id,
      total_pence: input.total_pence ?? null,
      fulfilment_method: input.fulfilment_method,
      staff_account_id: (accountId as string | null) ?? null,
    },
  });
}

// Switch a completed visit's fulfilment method after the fact. Customers
// sometimes change their mind between the visit and dispatch — we need
// to support flipping in_person → shipping and back without forcing the
// receptionist to "uncomplete" and redo the whole closing flow.
//
// Guard rails:
//   • Caller must pass the currently-stored method so a stale-page
//     submission can't silently overwrite a more recent change.
//   • Once a DPD label is issued (visit.dispatch_ref set), we refuse
//     to switch — orphaning a live shipment is worse than the customer
//     waiting for a manual cancel. The UI surfaces this state with a
//     "cancel the shipment first" note instead of the change button.
//   • Switching FROM shipping to in_person clears the
//     shipping_email_sent_at lock so a future shipping decision isn't
//     blocked by the atomic-claim that prevented duplicate emails.
//
// Audit:
//   patient_events 'visit_fulfilment_method_changed' with the old + new
//   methods, the visit id, and the actor. The timeline reads it via the
//   existing patient-events fetcher.
export interface UpdateVisitFulfilmentMethodInput {
  visit_id: string;
  patient_id: string;
  expected_current_method: VisitFulfilmentMethod;
  next_method: VisitFulfilmentMethod;
}

export type UpdateVisitFulfilmentMethodResult =
  | { ok: true; method: VisitFulfilmentMethod }
  | { ok: false; reason: 'no_change' | 'shipment_dispatched' | 'stale_method' | 'not_found' | 'update_failed'; detail?: string };

export async function updateVisitFulfilmentMethod(
  input: UpdateVisitFulfilmentMethodInput,
): Promise<UpdateVisitFulfilmentMethodResult> {
  if (input.expected_current_method === input.next_method) {
    return { ok: false, reason: 'no_change' };
  }

  // Re-read the row inside the same call so we catch a concurrent
  // change between the staff member opening the sheet and pressing
  // Confirm. The dispatch_ref check has to run against fresh data,
  // not the page's stale visit prop.
  const { data: fresh, error: readErr } = await supabase
    .from('lng_visits')
    .select('id, fulfilment_method, dispatch_ref')
    .eq('id', input.visit_id)
    .maybeSingle();
  if (readErr || !fresh) {
    return { ok: false, reason: 'not_found', detail: readErr?.message };
  }
  const current = (fresh as { fulfilment_method: VisitFulfilmentMethod | null }).fulfilment_method;
  if (current !== input.expected_current_method) {
    return { ok: false, reason: 'stale_method', detail: `Server has '${current}' (you saw '${input.expected_current_method}'). Refresh and try again.` };
  }
  const dispatchRef = (fresh as { dispatch_ref: string | null }).dispatch_ref;
  if (dispatchRef) {
    return { ok: false, reason: 'shipment_dispatched', detail: dispatchRef };
  }

  const patch: Record<string, unknown> = { fulfilment_method: input.next_method };
  // Free the dispatch-email lock when leaving shipping so the next
  // shipping attempt (if the customer flips again, or this same staff
  // member changes their mind) can re-send.
  if (input.expected_current_method === 'shipping' && input.next_method === 'in_person') {
    patch.shipping_email_sent_at = null;
  }

  const { error: updateErr } = await supabase
    .from('lng_visits')
    .update(patch)
    .eq('id', input.visit_id);
  if (updateErr) {
    return { ok: false, reason: 'update_failed', detail: updateErr.message };
  }

  const { data: accountId } = await supabase.rpc('auth_account_id');
  await supabase.from('patient_events').insert({
    patient_id: input.patient_id,
    event_type: 'visit_fulfilment_method_changed',
    actor_account_id: (accountId as string | null) ?? null,
    payload: {
      visit_id: input.visit_id,
      from_method: input.expected_current_method,
      to_method: input.next_method,
      staff_account_id: (accountId as string | null) ?? null,
    },
  });

  return { ok: true, method: input.next_method };
}

// Single entry point for the cart-line Remove sheet. Handles all
// three reason categories in one call: soft-deletes the line,
// writes the right audit row(s), and decides whether the visit
// should terminate as a result.
//
// Termination rule: visit flips to status='unsuitable' when the
// cart becomes empty AND at least one unsuitability record exists
// on this visit (in this removal or a prior one). Mixed visits
// where some removals were mistakes and at least one was
// unsuitable still terminate. Cart-empty-by-mistake-only visits
// stay active so staff can re-add.
export interface RemoveCartLineWithReasonInput {
  cart_item_id: string;
  catalogue_id: string | null; // required for 'unsuitable'
  visit_id: string;
  patient_id: string;
  reason: 'mistake' | 'changed_mind' | 'unsuitable';
  note?: string;
}

export async function removeCartLineWithReason(
  input: RemoveCartLineWithReasonInput
): Promise<{ visit_terminated: boolean }> {
  const { data, error } = await supabase.rpc('lng_remove_cart_line', {
    p_cart_item_id: input.cart_item_id,
    p_visit_id: input.visit_id,
    p_patient_id: input.patient_id,
    p_reason: input.reason,
    p_note: input.note ?? '',
    p_catalogue_id: input.catalogue_id,
  });
  if (error) throw new Error(error.message);
  const row = Array.isArray(data) ? (data[0] as { visit_terminated: boolean } | undefined) : null;
  return { visit_terminated: row?.visit_terminated === true };
}

// Reverse a visit that terminated as 'unsuitable' or 'ended_early'.
// Thin wrapper around lng_reverse_visit_end, which owns the atomic
// reverse transaction: restore the lines whose removed_reason
// signals they were taken by the visit-end action (unsuitable or
// visit_ended_early), reopen the visit, and write the timeline
// event.
//
// The reverse contract — only lines that were removed BY the
// visit-end action come back. Mid-visit 'mistake' and
// 'changed_mind' removals stay removed so the refunds already
// issued against those removals stay reconciled. (Earlier
// behaviour was "restore everything", which broke the cart vs
// refund accounting when a mid-visit refund pre-dated the visit-
// end action — see 20260519000006 migration header for the
// reasoning.)
//
// lng_unsuitability_records are immutable clinical audit and are
// never deleted by reverse — only the cart-item soft-delete is
// un-flagged.
export async function reverseUnsuitability(input: ReverseUnsuitabilityInput): Promise<void> {
  const { error } = await supabase.rpc('lng_reverse_visit_end', {
    p_visit_id: input.visit_id,
    p_patient_id: input.patient_id,
    p_note: null,
  });
  if (error) throw new Error(error.message);
}

// Latest end-of-visit details (either path: 'unsuitable' or
// 'ended_early'). The header lifecycle line uses these to render
// "Marked Unsuitable [time] / By [name]" or "Visit Ended Early
// [time] / By [name]". Null while the visit is still active.
//
// For 'unsuitable' the staff name comes from lng_unsuitability_records
// (the latest record's recorded_by). For 'ended_early' it comes
// from the latest patient_events row of type 'visit_ended_early'
// matching this visit.
export interface LatestUnsuitability {
  recorded_at: string;
  // The reason text shown beneath the header line. For unsuitable
  // it's the lng_unsuitability_records.reason from the latest
  // record; for ended_early it's lng_visits.visit_end_note.
  reason: string;
  recorded_by_name: string | null;
  // Discriminator so the header can render the right label.
  category: 'unsuitable' | 'ended_early';
  // Sub-category for 'ended_early' visits (patient_declined,
  // patient_walked_out, wrong_booking, other). Null when category
  // is 'unsuitable'.
  end_reason: VisitEndReason | null;
}

interface LatestUnsuitabilityResult {
  data: LatestUnsuitability | null;
  loading: boolean;
  error: string | null;
}

interface AccountJoin {
  first_name: string | null;
  last_name: string | null;
  name: string | null;
}

function displayAccountName(a: AccountJoin | AccountJoin[] | null | undefined): string | null {
  const flat = Array.isArray(a) ? a[0] ?? null : a ?? null;
  if (!flat) return null;
  const fn = flat.first_name?.trim();
  const ln = flat.last_name?.trim();
  if (fn && ln) return `${fn} ${ln}`;
  return fn ?? ln ?? flat.name?.trim() ?? null;
}

export function useLatestUnsuitability(visitId: string | null): LatestUnsuitabilityResult {
  const [data, setData] = useState<LatestUnsuitability | null>(null);
  const [error, setError] = useState<string | null>(null);
  const { loading, settle } = useStaleQueryLoading(visitId);

  useEffect(() => {
    if (!visitId) {
      setData(null);
      settle();
      return;
    }
    let cancelled = false;
    (async () => {
      // Step A: read the visit row to learn status + end reason/note.
      // Visits not in a terminal status return null — the header
      // shouldn't surface anything until the visit ends.
      const { data: vRow, error: vErr } = await supabase
        .from('lng_visits')
        .select('status, closed_at, visit_end_reason, visit_end_note')
        .eq('id', visitId)
        .maybeSingle();
      if (cancelled) return;
      if (vErr) {
        setError(vErr.message);
        settle();
        return;
      }
      const v = vRow as {
        status: string | null;
        closed_at: string | null;
        visit_end_reason: VisitEndReason | null;
        visit_end_note: string | null;
      } | null;
      if (!v || (v.status !== 'unsuitable' && v.status !== 'ended_early')) {
        setData(null);
        settle();
        return;
      }

      // Step B: pull the staff name. For 'unsuitable' we have the
      // recorded_by FK on the latest lng_unsuitability_records row;
      // for 'ended_early' it lives on the patient_events row this
      // function emits.
      if (v.status === 'unsuitable') {
        const { data: row, error: err } = await supabase
          .from('lng_unsuitability_records')
          .select('recorded_at, reason, account:accounts!recorded_by ( first_name, last_name, name )')
          .eq('visit_id', visitId)
          .order('recorded_at', { ascending: false })
          .limit(1)
          .maybeSingle();
        if (cancelled) return;
        if (err) {
          if (err.code === '42P01' || err.code === 'PGRST200') {
            setData(null);
            setError(null);
          } else {
            setError(err.message);
          }
          settle();
          return;
        }
        const r = row as { recorded_at: string; reason: string; account: AccountJoin | AccountJoin[] | null } | null;
        if (!r) {
          // status='unsuitable' without a record is the migration-
          // backfilled case; fall back to the visit's own end note
          // and skip the staff name.
          setData({
            recorded_at: v.closed_at ?? new Date(0).toISOString(),
            reason: v.visit_end_note ?? '',
            recorded_by_name: null,
            category: 'unsuitable',
            end_reason: null,
          });
          settle();
          return;
        }
        setData({
          recorded_at: r.recorded_at,
          reason: r.reason,
          recorded_by_name: displayAccountName(r.account),
          category: 'unsuitable',
          end_reason: null,
        });
        settle();
        return;
      }

      // status === 'ended_early'
      const { data: peRow, error: peErr } = await supabase
        .from('patient_events')
        .select('created_at, actor_account_id, account:accounts!actor_account_id ( first_name, last_name, name )')
        .eq('event_type', 'visit_ended_early')
        .filter('payload->>visit_id', 'eq', visitId)
        .order('created_at', { ascending: false })
        .limit(1)
        .maybeSingle();
      if (cancelled) return;
      if (peErr && peErr.code !== '42P01' && peErr.code !== 'PGRST200') {
        setError(peErr.message);
        settle();
        return;
      }
      const pe = peRow as { created_at: string; account: AccountJoin | AccountJoin[] | null } | null;
      setData({
        recorded_at: pe?.created_at ?? v.closed_at ?? new Date(0).toISOString(),
        reason: v.visit_end_note ?? '',
        recorded_by_name: displayAccountName(pe?.account),
        category: 'ended_early',
        end_reason: v.visit_end_reason,
      });
      settle();
    })();
    return () => {
      cancelled = true;
    };
  }, [visitId, settle]);

  return { data, loading, error };
}
