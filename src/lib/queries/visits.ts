// Records that staff rejoined an already-joined virtual meeting. No
// status flip — the appointment stays 'joined'. Writes a patient_events
// row so the timeline tracks every time the link was reopened.
//
// Throws on insert error rather than silently swallowing it. The
// previous version awaited `.insert()` without checking the response
// — Supabase doesn't reject on RLS denial, it returns the error in
// the response object — so an RLS misconfiguration would make every
// Rejoin tap appear to succeed while writing nothing. The caller in
// AppointmentDetail catches the throw and forwards it to logFailure
// so the audit trail stays loud.
export async function logVirtualMeetingRejoin(appointmentId: string, patientId: string): Promise<void> {
  const { data: accountId } = await supabase.rpc('auth_account_id');
  const { error } = await supabase.from('patient_events').insert({
    patient_id: patientId,
    event_type: 'virtual_meeting_rejoined',
    actor_account_id: (accountId as string | null) ?? null,
    payload: {
      appointment_id: appointmentId,
      rejoined_at: new Date().toISOString(),
    },
  });
  if (error) throw new Error(error.message);
}

export interface MarkAppointmentArrivedInput {
  appointment_id: string;
  // Tech note typed on the arrival form's Step 1 (Service). Carries
  // straight to lng_visits.notes so VisitDetail's "Edit tech note"
  // button reads what the receptionist captured at arrival rather
  // than showing "Add tech note" on a visit that already has one.
  // Pre-RPC, only the walk-in path wrote this; appointment arrivals
  // silently dropped the textarea on the floor.
  notes?: string;
}

export async function markAppointmentArrived(
  input: MarkAppointmentArrivedInput
): Promise<{ visit_id: string; opened_at: string }> {
  const trimmedNotes = input.notes?.trim();
  const notesToWrite = trimmedNotes && trimmedNotes.length > 0 ? trimmedNotes : null;

  const { data: appt, error: apptErr } = await supabase
    .from('lng_appointments')
    .update({ status: 'arrived' })
    .eq('id', input.appointment_id)
    .select('id, patient_id, location_id')
    .single();
  if (apptErr || !appt) throw new Error(apptErr?.message ?? 'Could not mark arrived');

  // Stamp the receptionist who checked the patient in so the
  // timeline's "Patient checked in" + "Job box assigned" events can
  // attribute by [name]. Best-effort: if the account resolver fails
  // (kiosk session edge case) the column lands NULL rather than
  // blocking arrival.
  const { data: accountIdAtArrival } = await supabase.rpc('auth_account_id');
  const receptionistId = (accountIdAtArrival as string | null) ?? null;

  // Returning opened_at lets the caller pass it through router state
  // so the visit page's breadcrumb renders the timestamp on first
  // paint — no shimmer-then-pop transition.
  const { data: visit, error: visitErr } = await supabase
    .from('lng_visits')
    .insert({
      patient_id: appt.patient_id,
      location_id: appt.location_id,
      appointment_id: appt.id,
      arrival_type: 'scheduled',
      status: 'arrived',
      receptionist_id: receptionistId,
      notes: notesToWrite,
    })
    .select('id, opened_at')
    .single();
  if (visitErr || !visit) throw new Error(visitErr?.message ?? 'Could not create visit');

  await supabase.from('patient_events').insert({
    patient_id: appt.patient_id,
    event_type: 'visit_arrived',
    actor_account_id: receptionistId,
    payload: { visit_id: visit.id, appointment_id: appt.id, source: 'calendly' },
  });

  return {
    visit_id: visit.id,
    opened_at: (visit as { opened_at: string }).opened_at,
  };
}

// Calendly deposit captured at booking time, surfaced through the visit
// so the Pay screen can deduct it from the bill. Null on walk-ins (no
// underlying appointment) and on Calendly bookings whose event type
// doesn't take a deposit.
//
// status = 'paid'   ready to credit at checkout
// status = 'failed' attempt recorded but not collected — the till must NOT
//                   credit it; receptionist should chase.
export interface AppointmentDeposit {
  pence: number;
  currency: string;
  provider: 'paypal' | 'stripe';
  status: 'paid' | 'failed';
  // Where the booking + deposit originated. 'native' means the online
  // widget (venneir.com / denture-services.co.uk); 'calendly' means a
  // Calendly checkout. Drives the "via …" suffix on Pay screen and
  // waiver so a widget deposit doesn't read as a Calendly one.
  source: string | null;
  // brand_id of the booking — 'venneir' or 'denture'. Picks the
  // customer-facing domain in the source suffix ("venneir.com" vs
  // "denture-services.co.uk"). Null when the column wasn't populated
  // (legacy rows); callers default to 'venneir' for safety.
  brandId: 'venneir' | 'denture' | null;
  // True when the widget collected the FULL service price up-front,
  // not just a deposit. Pay screen + waiver use this to switch the
  // line label from "Deposit" to "Paid in full". Always false for
  // Calendly bookings (Calendly only takes deposits).
  paidInFullAtBooking: boolean;
}

/** Bracketed suffix shown after a deposit line on every staff
 *  surface (Pay screen, VisitDetail Cart, waiver PDF) — e.g.
 *  "Stripe via Calendly" / "Stripe via venneir.com" / "PayPal via
 *  denture-services.co.uk". Source 'native' means the online widget,
 *  with the brand id picking the customer-facing domain. Calendly
 *  deposits keep the legacy label so historical receipts stay
 *  consistent; null source defaults to Calendly so legacy rows
 *  written before the source/brand columns existed don't suddenly
 *  relabel. */
export function formatDepositSourceSuffix(deposit: AppointmentDeposit | null): string {
  const provider = deposit?.provider === 'stripe' ? 'Stripe' : 'PayPal';
  if (deposit?.source === 'native') {
    const brand = deposit.brandId === 'denture' ? 'denture-services.co.uk' : 'venneir.com';
    return `${provider} via ${brand}`;
  }
  return `${provider} via Calendly`;
}

